@app.post("/inference", response_model=InferenceResponse)
async def inference(req: InferenceRequest, request: Request):
    """
    Payment-guarded inference endpoint.

    Flow:
      1. Verify escrow (or wallet) on Solana.
      2. Route prompt to the model endpoint.
      3. Call complete_inference on-chain.
      4. Return the inference result + tx signature.
    """
    start = time.perf_counter()
    request_id = str(uuid.uuid4())

    # Step 1 — payment guard
    if req.walletAddress:
        escrow_valid = await verify_escrow(
            req.escrowPubkey or "", req.walletAddress
        )
        if not escrow_valid:
            raise HTTPException(status_code=402, detail="Escrow not found or already consumed")

    # Step 2 — resolve model
    model_info = MODEL_REGISTRY.get(req.modelId)
    if model_info:
        endpoint = model_info["api_endpoint"]
        model_id = model_info.get("model_id", DEFAULT_OPENROUTER_MODEL)
        # Use OpenRouter if endpoint is OPENROUTER_BASE_URL
        if endpoint == OPENROUTER_BASE_URL:
            text, tokens = await call_openrouter(req.prompt, model_id)
        else:
            text, tokens = await call_model_endpoint(
                endpoint, req.prompt, req.walletAddress or ""
            )
    else:
        # Unknown model — route through default OpenRouter model
        text, tokens = await call_openrouter(req.prompt, DEFAULT_OPENROUTER_MODEL)

    # Step 3 — release escrow on-chain
    tx_sig = None
    if req.escrowPubkey:
        tx_sig = await complete_inference_on_chain(req.escrowPubkey, req.modelId)

    latency_ms = int((time.perf_counter() - start) * 1000)

    return InferenceResponse(
        text=text,
        modelId=req.modelId,
        tokensUsed=tokens,
        latencyMs=latency_ms,
        txSignature=tx_sig,
        requestId=request_id,
    )


