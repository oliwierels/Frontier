# ── Inference routing ─────────────────────────────────────────────────────────


async def call_openrouter(prompt: str, model_id: str) -> tuple[str, int]:
    """Route inference to OpenRouter. Falls back to mock if key not set."""
    if not OPENROUTER_API_KEY:
        # Demo fallback — deterministic mock
        mock_text = (
            f"[DEMO MODE] This response is generated by the Lumina inference mock. "
            f"In production, your prompt '{prompt[:60]}...' would be routed to "
            f"{model_id} via OpenRouter, with payment verified on-chain before "
            f"forwarding."
        )
        return mock_text, len(prompt.split())

    async with httpx.AsyncClient() as client:
        resp = await client.post(
            f"{OPENROUTER_BASE_URL}/chat/completions",
            headers={
                "Authorization": f"Bearer {OPENROUTER_API_KEY}",
                "HTTP-Referer": "https://lumina.ai",
                "X-Title": "Lumina AI Marketplace",
            },
            json={
                "model": model_id,
                "messages": [{"role": "user", "content": prompt}],
                "max_tokens": 512,
            },
            timeout=30.0,
        )
        resp.raise_for_status()
        data = resp.json()
        text = data["choices"][0]["message"]["content"]
        tokens = data.get("usage", {}).get("total_tokens", 0)
        return text, tokens


async def call_model_endpoint(endpoint: str, prompt: str, wallet_address: str) -> tuple[str, int]:
    """Call a creator's custom API endpoint."""
    async with httpx.AsyncClient() as client:
        resp = await client.post(
            endpoint,
            json={"prompt": prompt, "walletAddress": wallet_address},
            timeout=30.0,
        )
        resp.raise_for_status()
        data = resp.json()
        return data.get("text", ""), data.get("tokensUsed", 0)


