# ── Escrow verification ───────────────────────────────────────────────────────


async def verify_escrow(escrow_pubkey: str, wallet_address: str) -> bool:
    """
    Calls the Solana RPC to confirm the escrow PDA exists and is unfulfilled.
    In production this uses solders / anchorpy to deserialise the account.
    For the demo it performs a simple account-existence check.
    """
    if not escrow_pubkey:
        # Allow wallet-only flow (demo / devnet without funded accounts)
        return True

    async with httpx.AsyncClient() as client:
        try:
            resp = await client.post(
                SOLANA_RPC_URL,
                json={
                    "jsonrpc": "2.0",
                    "id": 1,
                    "method": "getAccountInfo",
                    "params": [
                        escrow_pubkey,
                        {"encoding": "base64"},
                    ],
                },
                timeout=5.0,
            )
            data = resp.json()
            account = data.get("result", {}).get("value")
            return account is not None
        except Exception:
            # Network failure — allow in dev mode
            return True


